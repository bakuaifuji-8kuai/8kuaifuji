/**
 * 验收附件演示种子（仅首次进入验收页执行一次）
 * =========================================================
 * 用 canvas 生成 2 张"现场验收照片示意"JPEG + 1 个规范的占位 PDF，
 * 写入 IndexedDB 并挂到 1 条已通过且尚无附件的验收记录上，
 * 让附件功能开箱即可看到效果。不触碰真实用户数据：
 * - 只选 status=approved 且 attachments 为空的记录
 * - localStorage 标记位保证只执行一次
 * - idb 不可用直接跳过（标记 unsupported）
 * =========================================================
 */
import type { Attachment, ProcurementInspection } from '@/types';
import { toIdbRef, nowText } from '@/utils/fileHelper';
import { isAttachmentDbSupported, putAttachmentBlob } from '@/utils/attachmentDB';

const FLAG = 'wms-inspection-att-seed-v1';

/** 生成一张示意现场照片（JPEG Blob） */
function drawDemoPhoto(title: string, scene: string, accent: string): Promise<Blob> {
  return new Promise((resolve, reject) => {
    const w = 960;
    const h = 600;
    const canvas = document.createElement('canvas');
    canvas.width = w;
    canvas.height = h;
    const ctx = canvas.getContext('2d');
    if (!ctx) {
      reject(new Error('canvas 不可用'));
      return;
    }

    // 背景渐变（模拟现场环境）
    const grad = ctx.createLinearGradient(0, 0, w, h);
    grad.addColorStop(0, '#e8edf5');
    grad.addColorStop(1, '#cfd8e8');
    ctx.fillStyle = grad;
    ctx.fillRect(0, 0, w, h);

    // 地面
    ctx.fillStyle = '#b8c2d4';
    ctx.fillRect(0, h * 0.68, w, h * 0.32);

    // 简单"设备/展台"几何示意
    ctx.fillStyle = '#ffffff';
    ctx.strokeStyle = accent;
    ctx.lineWidth = 4;
    ctx.fillRect(180, 200, 360, 220);
    ctx.strokeRect(180, 200, 360, 220);
    ctx.fillStyle = accent;
    ctx.fillRect(220, 240, 120, 60);
    ctx.fillStyle = '#94a3b8';
    ctx.fillRect(380, 240, 120, 60);
    ctx.fillStyle = '#cbd5e1';
    for (let i = 0; i < 3; i++) ctx.fillRect(220 + i * 110, 340, 80, 50);

    // 人物简形
    ctx.fillStyle = '#64748b';
    ctx.beginPath();
    ctx.arc(650, 300, 26, 0, Math.PI * 2);
    ctx.fill();
    ctx.fillRect(624, 330, 52, 100);

    // 顶部标题条
    ctx.fillStyle = 'rgba(99,102,241,0.92)';
    ctx.fillRect(0, 0, w, 70);
    ctx.fillStyle = '#ffffff';
    ctx.font = 'bold 30px "Microsoft YaHei", sans-serif';
    ctx.fillText(title, 32, 46);

    // 底部信息条
    ctx.fillStyle = 'rgba(15,23,42,0.72)';
    ctx.fillRect(0, h - 64, w, 64);
    ctx.fillStyle = '#ffffff';
    ctx.font = '20px "Microsoft YaHei", sans-serif';
    ctx.fillText(scene, 32, h - 36);
    ctx.font = '14px "Microsoft YaHei", sans-serif';
    ctx.fillStyle = '#cbd5e1';
    ctx.fillText(`拍摄时间：${nowText()}    （演示数据，非真实照片）`, 32, h - 14);

    canvas.toBlob((b) => (b ? resolve(b) : reject(new Error('JPEG 编码失败'))), 'image/jpeg', 0.82);
  });
}

/** 生成一份结构合法的单页 PDF（纯 ASCII，手工构建 xref 偏移） */
function buildDemoPdf(): Blob {
  const lines = [
    'BT /F1 20 Tf 60 790 Td (Inspection Stamped Document - DEMO) Tj ET',
    'BT /F1 12 Tf 60 758 Td (Acceptance stamped materials, auto-generated for demo.) Tj ET',
    'BT /F1 12 Tf 60 740 Td (Please replace with the real scanned copy.) Tj ET',
    'BT /F1 10 Tf 60 120 Td (Generated by WMS static demo, local browser only.) Tj ET',
  ];
  const stream = lines.join('\n');

  let pdf = '%PDF-1.4\n';
  const offsets: number[] = [];
  const addObj = (n: number, body: string) => {
    offsets[n - 1] = pdf.length;
    pdf += `${n} 0 obj\n${body}\nendobj\n`;
  };

  addObj(1, '<< /Type /Catalog /Pages 2 0 R >>');
  addObj(2, '<< /Type /Pages /Kids [3 0 R] /Count 1 >>');
  addObj(3, '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>');
  addObj(4, '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');
  addObj(5, `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`);

  const xrefStart = pdf.length;
  pdf += 'xref\n0 6\n';
  pdf += '0000000000 65535 f \r\n';
  offsets.forEach((off) => {
    pdf += `${String(off).padStart(10, '0')} 00000 n \r\n`;
  });
  pdf += `trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF`;

  return new Blob([pdf], { type: 'application/pdf' });
}

export async function ensureInspectionAttachmentSeeds(
  inspections: ProcurementInspection[],
  update: (id: string, data: Partial<ProcurementInspection>) => void,
): Promise<void> {
  if (typeof localStorage === 'undefined') return;
  if (localStorage.getItem(FLAG)) return;

  try {
    const supported = await isAttachmentDbSupported();
    if (!supported) {
      localStorage.setItem(FLAG, 'unsupported');
      return;
    }

    // 只挑一条已通过、且没有附件的验收记录
    const target = inspections.find(
      (i) => i.status === 'approved' && (!i.attachments || i.attachments.length === 0),
    );
    if (!target) {
      localStorage.setItem(FLAG, 'done');
      return;
    }

    const photo1 = await drawDemoPhoto('现场验收照片 ①', '设备外观与铭牌核对', '#6366f1');
    const photo2 = await drawDemoPhoto('现场验收照片 ②', '安装位置及通电测试', '#8b5cf6');
    const pdf = buildDemoPdf();

    const items: Array<{ blob: Blob; att: Omit<Attachment, 'filePath'> }> = [
      {
        blob: photo1,
        att: {
          id: `ATT-SEED-${target.id}-1`,
          fileName: '现场验收照片01-外观核对.jpg',
          fileSize: photo1.size,
          fileType: 'image/jpeg',
          uploadTime: target.inspectionDate ? `${target.inspectionDate} 10:20:00` : nowText(),
          category: 'site_photo',
        },
      },
      {
        blob: photo2,
        att: {
          id: `ATT-SEED-${target.id}-2`,
          fileName: '现场验收照片02-通电测试.jpg',
          fileSize: photo2.size,
          fileType: 'image/jpeg',
          uploadTime: target.inspectionDate ? `${target.inspectionDate} 10:25:00` : nowText(),
          category: 'site_photo',
        },
      },
      {
        blob: pdf,
        att: {
          id: `ATT-SEED-${target.id}-3`,
          fileName: '验收盖章确认单（演示）.pdf',
          fileSize: pdf.size,
          fileType: 'application/pdf',
          uploadTime: target.inspectionDate ? `${target.inspectionDate} 11:00:00` : nowText(),
          category: 'stamped_doc',
        },
      },
    ];

    const attachments: Attachment[] = [];
    for (const it of items) {
      await putAttachmentBlob(it.att.id, it.blob);
      attachments.push({ ...it.att, filePath: toIdbRef(it.att.id) });
    }

    update(target.id, { attachments });
    localStorage.setItem(FLAG, 'done');
  } catch {
    // 失败不重试，避免每次进页面都跑；真实上传功能不受影响
    try { localStorage.setItem(FLAG, 'error'); } catch { /* ignore */ }
  }
}
